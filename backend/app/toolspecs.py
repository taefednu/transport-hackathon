# рамку расчёта молча: на вопрос про утро приходит суббота, числа расходятся с
# движком, и разойтись они могут незаметно — охрана чисел этого не ловит,
# потому что числа настоящие, просто не про то.
TOOL_SCHEMA = {
    "type": "object",
    "properties": {
        "tool": {"type": "string", "enum": [*TOOL_NAMES, "answer", "out_of_scope"]},
        "route_num": {"type": "string"},
        "direction": {"type": "string", "enum": ["fwd", "bwd"]},
        "text": {"type": "string"},
        "limit": {"type": "integer"},
    },
    # Яндекс отвергает схему, где required — подмножество свойств
    "required": ["tool", "route_num", "direction", "text", "limit"],
    "additionalProperties": False,
}


def tool_user(question: str, hints: dict, done: list[dict]) -> str:
    """Вопрос, подсказки резолва по базе и то, что уже посчитано."""
    parts = [f"Вопрос планировщика: «{question}»"]
    if hints:
        parts.append("Подсказки поиска по базе: " + json.dumps(hints, ensure_ascii=False))
    if done:
        parts.append(
            "Уже вызвано и посчитано:\n"
            + json.dumps(done, ensure_ascii=False)[: config.ASSISTANT_DONE_PROMPT_CHARS]
        )
        parts.append("Если этого хватает для ответа — выбери answer.")
    parts.append("Выбери инструмент.")
    return "\n\n".join(parts)



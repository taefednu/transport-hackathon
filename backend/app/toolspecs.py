def tools_text() -> str:
    """Список инструментов для модели."""
    lines = []
    for tool in TOOLS:
        params = ", ".join(f"{k} — {v}" for k, v in tool["params"].items())
        line = f"- {tool['name']}: {tool['summary']}. Параметры: {params}."
        if tool.get("detail"):
            line += f" {tool['detail']}"
        line += f" Спрашивают так: {tool['when']}."
        lines.append(line)
    return "\n".join(lines)



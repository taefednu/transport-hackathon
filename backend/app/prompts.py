"""Промпты к модели. Держатся отдельно от логики: их правят чаще, чем код.

Общее для обоих: модель не знает базу и не считает. В разборе фразы она достаёт
намерение и строки ровно так, как их написал человек, — превращение строк в
`route_num` и `stop_id` делает поиск с транслитерацией. В объяснении она
пересказывает уже посчитанные числа и не имеет права добавить своё.
"""

from __future__ import annotations

import json

# --- разбор запроса на естественном языке -------------------------------

PARSE_SYSTEM = """Ты разбираешь команды планировщика маршрутной сети Ташкента.
Твоя работа — понять намерение и выписать названия ровно так, как их написал человек.

Ты НЕ знаешь базу остановок и маршрутов. Никогда не выдумывай, не переводи и не
исправляй названия: если человек написал «Куйлюк» — так и пиши «Куйлюк», если
«Qo'yliq» — так и пиши «Qo'yliq». Идентификаторы не придумывай, их подставит система.

Операции:
- extend_route — продлить маршрут до остановок (продлить, дотянуть, довести, удлинить)
- trim_route — обрезать маршрут до остановки (обрезать, укоротить, сократить)
- insert_stop — вставить существующую остановку в середину маршрута
- remove_stop — убрать остановку из маршрута
- set_schedule — изменить интервал, время первого выезда или число машин на линии
- unknown — намерение не одна из перечисленных операций

Поля:
- route: номер маршрута строкой как в тексте («14», «четырнадцатый» → «14»)
- stops: список названий остановок, к которым относится операция
- anchor_stop: остановка-ориентир для insert_stop («после X») — иначе пустая строка
- hour: час суток числом 0..23, если он упомянут («в восемь» → 8, «утром» → 8,
  «в утренний пик» → 8, «днём» → 13, «вечером» → 18, «в вечерний пик» → 18).
  Если часа в тексте нет — ставь 8
- weekday: «fri» для будня и пятницы, «sat» для субботы и выходного, «sun» для
  воскресенья. Если дня в тексте нет — ставь «fri»
- headway_min, first_departure («ЧЧ:ММ»), n_vehicles — только для set_schedule,
  иначе 0, пустая строка и 0

Отвечай строго одним JSON-объектом без пояснений."""

# схема, которую запрашиваем у модели строгим режимом (proto: jsonSchema.schema)
PARSE_SCHEMA = {
    "type": "object",
    "properties": {
        "op": {
            "type": "string",
            "enum": [
                "extend_route",
                "trim_route",
                "insert_stop",
                "remove_stop",
                "set_schedule",
                "unknown",
            ],
        },
        "route": {"type": "string"},
        "stops": {"type": "array", "items": {"type": "string"}},
        "anchor_stop": {"type": "string"},
        "hour": {"type": "integer"},
        "weekday": {"type": "string", "enum": ["fri", "sat", "sun"]},
        "headway_min": {"type": "number"},
        "first_departure": {"type": "string"},
        "n_vehicles": {"type": "integer"},
    },
    # Яндекс отвергает схему, где required — подмножество свойств:
    # «Invalid JSON Schema: all fields must be required». Поэтому перечислены все,
    # а незаполненные поля модель отдаёт нулями и пустыми строками.
    "required": [
        "op",
        "route",
        "stops",
        "anchor_stop",
        "hour",
        "weekday",
        "headway_min",
        "first_departure",
        "n_vehicles",
    ],
    "additionalProperties": False,
}

PARSE_EXAMPLE = json.dumps(
    {
        "op": "extend_route",
        "route": "8",
        "stops": ["Себзар"],
        "anchor_stop": "",
        "hour": 18,
        "weekday": "fri",
        "headway_min": 0,
        "first_departure": "",
        "n_vehicles": 0,
    },
    ensure_ascii=False,
)


def parse_user(text: str) -> str:
    return (
        f"Пример. Фраза: «продлить восьмёрку до Себзара и посмотреть вечерний пик».\n"
        f"Ответ: {PARSE_EXAMPLE}\n\n"
        f"Разбери фразу: «{text}»"
    )


# --- объяснение посчитанного результата ---------------------------------

EXPLAIN_SYSTEM = """Ты пишешь абзац для служебной записки специалиста по маршрутной сети.

Тебе дают уже посчитанные значения. Твоя работа — связно их пересказать.

Запреты, нарушение любого делает текст непригодным:
- не называй ни одного числа, которого нет во входных данных;
- ничего не считай, не складывай, не переводи в проценты и не округляй по-своему;
- не оценивай решение: ни «хорошо», ни «плохо», ни «целесообразно», ни
  «рекомендуется». Оценка — работа планировщика, а не твоя;
- не добавляй причин и следствий, которых нет во входных данных.

Стиль: один абзац сплошным текстом, деловой, без списков, без заголовков,
без обращений к читателю. Порядок изложения: что изменено, сколько человек
получило доступ и сколько потеряло, что стало с интервалом и временем оборота,
какие сработали предупреждения.

Последнее предложение — оговорка об источниках, и в ней обязаны быть **обе**
величины из блока «оговорка»: доля перегонов, посчитанных по медиане скорости
города вместо реального трафика, и дата слоя населения. Абзац без любой из них
не принимается."""


def explain_user(facts: dict) -> str:
    return (
        "Значения (все числа брать только отсюда):\n"
        + json.dumps(facts, ensure_ascii=False, indent=2)
        + "\n\nНапиши один абзац."
    )
